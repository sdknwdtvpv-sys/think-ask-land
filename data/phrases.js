/* ============ 思问岛 · App 口播文案登记表(打招呼 / 表扬 / 任务完成) ============
   为什么要有这个文件:
     字卡里的字、词、例句早就做成了预置音频,但 App 自己的"口播"——
     「答对了,真棒」「早上好,我们一起来认字吧」——一直是写死在代码里的字符串,
     只能走浏览器 TTS。后果有两个:
       ① 表扬是系统音色,字卡是智小虎,一次体验里听到两个声音;
       ② iOS 主屏幕 APP 里 TTS 常常不出声 —— 孩子答对了却什么也听不到。
     把口播登记在这里,.build/gen-audio.py 会连它们一起合成预置音频(kind = p),
     于是全站一个音色、离线可用、独立 APP 也一定响。

   ⚠️ 改这里的任何一条,都要与代码里的实际口播保持一一对应 ——
      .build/phrase-test.js 会扫代码里所有 Speech.speak 的字面量并核对,
      新增一句口播却忘了登记,测试会直接失败。

   注意:动态拼接的句子也要"落到固定句"才能预置(例如连对报数改成固定一句
   「连对啦,太厉害了!」,数字继续在屏幕上显示)。
*/
